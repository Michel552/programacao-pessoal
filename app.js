function mostrarPeriodo() {

    const periodoSelecionado = dados.periodos.find(
            p => p.id === seletor.value
        );

const totalIdas = periodoSelecionado.eventos.filter(
        e => e.STATUS === "IDA"
    ).length;

const totalVoltas = periodoSelecionado.eventos.filter(
        e => e.STATUS === "VOLTA"
    ).length;

const totalNV = periodoSelecionado.eventos.filter(
        e => e.STATUS === "NV"
    ).length;

const eventosRelevantes = periodoSelecionado.eventos.filter(
        e =>
            e.STATUS === "FE" ||
            e.STATUS === "HO" ||
            e.STATUS === "FAMILIA_EM_SLZ" ||
            e.STATUS === "FAMILIA_VIAJA"
    );

dashboard.innerHTML = `

<div class="dashboard">

    <div class="dashboard-card">
        ✈️<br>
        ${totalIdas}<br>
        IDAS
    </div>

    <div class="dashboard-card">
        🛬<br>
        ${totalVoltas}<br>
        VOLTAS
    </div>

    <div class="dashboard-card">
        ⛔<br>
        ${totalNV}<br>
        NV
    </div>

    <div class="dashboard-card">
        ⭐<br>
        ${eventosRelevantes.length}<br>
        EVENTOS
    </div>

</div>

`;

const meses = {};

periodoSelecionado.eventos.forEach(evento => {

    if (!meses[evento.MES]) {
        meses[evento.MES] = [];
    }

    meses[evento.MES].push(evento);

});

let html = "";

for (const mes in meses) {


let linhaTempo = "";

meses[mes].forEach(evento => {

const inicio =
    formatarData(evento.DATA_INICIO);

const periodo =
    inicio.substring(0, 2);

    linhaTempo += `
        <div class="timeline-item">

            ${iconeStatus(evento.STATUS)}
            ${periodo}

        </div>
    `;

});


html += `
    <div class="mes-card">

        <h2
            class="mes-titulo"
            onclick="toggleMes('${mes}')">

            ${mes}
            (${meses[mes].length} eventos)

        </h2>

<div class="timeline">
    ${linhaTempo}
</div>

<div
    id="mes-${mes}"
    class="mes-conteudo">

    <div class="eventos-grid">
`;



    meses[mes].forEach(evento => {

        html += `
    <div class="card">

        <div
            class="status"
            style="color:${corStatus(evento.COR_STATUS)}">

            ${evento.STATUS}
	    <span class="data-inline">
            | ${periodoEvento(evento)}
            </span>

        </div>

        <div class="linha2">
            ${evento.CIA || ""}
            ${evento.CIA ? " | " : ""}
            ${evento.ORIGEM || ""}
            ${evento.DESTINO ? " → " : ""}
            ${evento.DESTINO || ""}
        </div>

        <div class="linha3">
            ${evento.HORA_INICIO || ""}
            ${evento.HORA_FIM ? " - " + evento.HORA_FIM : ""}
        </div>

        <div class="descricao">
            ${evento.DESCRICAO}
        </div>

    </div>
`;

    });

    html += `
            </div>
        </div>
    </div>
`;

}

    conteudo.innerHTML = html;

}

seletor.addEventListener(
    "change",
    mostrarPeriodo
);

mostrarPeriodo();